# =========================================================================
# 品类词：拼在商品名里，让"手机""耳机"这类关键词能搜到
# 顺序必须和 BASE 里每个分类的 10 条一一对应；留空表示该条名称里已经有品类词
# =========================================================================
TYPE_WORDS = {
    1: ["智能手机", "智能手机", "智能手机", "头戴式耳机", "平板电脑",
        "智能手表", "", "", "", ""],
    2: [""] * 10,
    3: ["", "", "", "支撑跑鞋", "", "", "", "", "", ""],
    4: ["", "", "", "", "绿茶", "", "", "", "", ""],
    5: ["计算机图书", "计算机图书", "计算机图书", "计算机图书", "计算机图书",
        "小说", "科幻小说", "", "", "桌游"],
    6: ["", "", "", "", "", "遮阳天幕", "", "", "", ""],
    7: [""] * 10,
    8: ["游戏本", "轻薄本", "", "", "", "", "", "", "", ""],
}


def sql_escape(text: str) -> str:
    """转义单引号（MySQL 用 '' 转义，这里直接换中文引号更好读）。"""
    return text.replace("'", "’").replace("\\", "＼")


def main() -> None:
    parser = argparse.ArgumentParser(description="生成商品测试数据 SQL")
    parser.add_argument("--per-category", type=int, default=50, help="每个分类生成多少件")
    args = parser.parse_args()

    rnd = random.Random(20261028)
    out: list[str] = [
        "-- 由 tools/gen_products.py 自动生成，请勿手改",
        "-- 商品图片是本地生成的商品卡（tools/gen_images.py），不依赖外网",
        "",
        "SET NAMES utf8mb4;",
        "",
        "DELETE FROM product;",
        "DELETE FROM category;",
        "",
        "INSERT INTO category (id, name, icon, parent_id, sort, status) VALUES",
    ]
    out.append(",\n".join(
        f"({cid}, '{sql_escape(cn)}', '{icon}', 0, {cid}, 1)"
        for cid, _slug, cn, icon in CATEGORIES
    ) + ";")
    out.append("")

    total = 0
    for cid, slug, cn_name, _icon in CATEGORIES:
        entries = BASE[cid]
        usages = USAGE[cid]
        rows: list[str] = []
        idx = 0

        # 每条商品自带 5 个规格，10 条 × 5 = 50 件
        while len(rows) < args.per_category:
            entry_i = idx % len(entries)
            vpos = (idx // len(entries)) % VARIANTS_LEN   # 第几个规格档位
            brand, line, base_price, tagline, specs, core, variants = entries[entry_i]
            variant = variants[vpos]
            idx += 1

            # 名称 = 品牌 + 系列 + 品类词 + 规格（品类词为空时自动跳过）
            # 加品类词是为了让"手机""耳机"这类关键词能搜到商品，
            # 否则名字里只有型号（Redmi K70），搜"手机"是 0 条。
            type_word = TYPE_WORDS.get(cid, [""] * 10)[entry_i]
            name = " ".join(x for x in (brand, line, type_word, variant) if x)
            # ★ 价格系数按"规格档位"取，不能按 idx 取 ★
            #   否则同一条商品的不同规格会算出同一个价格
            ratio = RATIOS[vpos % len(RATIOS)]
            sale = (Decimal(base_price) * Decimal(str(ratio))).quantize(Decimal("0.01"))
            original = (sale * Decimal(str(round(rnd.uniform(1.10, 1.25), 2)))).quantize(Decimal("0.01"))

            stock = rnd.randint(30, 300)
            sales = rnd.randint(80, 6000)

            specs_text = "、".join(
                f"{kv.split(':')[0]} {kv.split(':')[1]}" for kv in specs.split(";") if ":" in kv
            )
            desc = (
                f"{core}。主要参数：{specs_text}。"
                f"{usages[len(rows) % len(usages)]}"
                f"支持七天无理由退换（不影响二次销售）。"
            )

            spec_json = {}
            for kv in specs.split(";"):
                if ":" in kv:
                    k, v = kv.split(":", 1)
                    spec_json[k] = v
            spec_json["规格"] = variant

            # 图片：本地生成的商品卡（tools/gen_images.py 负责渲染）
            # 命名规则两边必须一致：{分类ID}_{款式序号}_{规格序号}.jpg
            # 这样一个款式 5 个规格共用同一张图（真实电商也是同款共用主图），
            # 不同款式之间绝不会串图。
            key = f"{cid}_{entry_i:02d}_{vpos}"
            cover = f"/images/gen/{key}.jpg"
            gallery = []          # 商品卡只有一张，没有多角度图

            rows.append(
                "({cid}, '{name}', '{sub}', '{desc}', '{spec}', '{cover}', '{imgs}', "
                "{price}, {orig}, {stock}, {sales}, 1)".format(
                    cid=cid,
                    name=sql_escape(name),
                    sub=sql_escape(tagline),
                    desc=sql_escape(desc),
                    spec=sql_escape(json.dumps(spec_json, ensure_ascii=False)),
                    cover=cover,
                    imgs=json.dumps(gallery),
                    price=sale, orig=original, stock=stock, sales=sales,
                )
            )

        out.append(
            "INSERT INTO product (category_id, name, subtitle, description, specs, "
            "cover, images, price, original_price, stock, sales, status) VALUES"
        )
        out.append(",\n".join(rows) + ";")
        out.append("")
        total += len(rows)
        print(f"[{cn_name}] {len(rows)} 件")

    OUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUT_FILE.write_text("\n".join(out), encoding="utf-8")
    print("=" * 46)
    print(f"共 {total} 件，写入 {OUT_FILE}")
    print(f"文件大小 {OUT_FILE.stat().st_size / 1024:.1f} KB")


if __name__ == "__main__":
    main()
